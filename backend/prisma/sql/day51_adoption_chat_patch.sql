\set ON_ERROR_STOP on

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

DO $$
BEGIN
  CREATE TYPE "AdoptionChatParticipantRole" AS ENUM ('adopter', 'shelter');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE public.adoption_chat_participants (
  thread_id uuid NOT NULL,
  user_id uuid NOT NULL,
  role "AdoptionChatParticipantRole" NOT NULL,
  last_read_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_read_sequence bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT adoption_chat_participants_pkey
    PRIMARY KEY (thread_id, user_id),
  CONSTRAINT adoption_chat_participants_thread_role_key
    UNIQUE (thread_id, role),
  CONSTRAINT adoption_chat_participants_thread_fkey
    FOREIGN KEY (thread_id)
    REFERENCES public.adoption_chat_threads(id)
    ON DELETE CASCADE,
  CONSTRAINT adoption_chat_participants_user_fkey
    FOREIGN KEY (user_id)
    REFERENCES public.users(id)
    ON DELETE RESTRICT,
  CONSTRAINT adoption_chat_participants_last_read_sequence_check
    CHECK (last_read_sequence >= 0)
);

CREATE OR REPLACE FUNCTION public.enforce_adoption_chat_participant_role()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  expected_user_id uuid;
BEGIN
  IF (
    TG_OP = 'UPDATE'
    AND NEW.last_read_sequence < OLD.last_read_sequence
  ) THEN
    RAISE EXCEPTION
      'Chat read sequence cannot move backwards'
      USING ERRCODE = '23514';
  END IF;

  SELECT CASE
    WHEN NEW.role = 'adopter' THEN adopter_user_id
    WHEN NEW.role = 'shelter' THEN shelter_id
  END
  INTO expected_user_id
  FROM public.adoption_chat_threads
  WHERE id = NEW.thread_id;

  IF expected_user_id IS NULL OR expected_user_id <> NEW.user_id THEN
    RAISE EXCEPTION
      'Chat participant does not match the thread role'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END
$$;

REVOKE ALL
  ON FUNCTION public.enforce_adoption_chat_participant_role()
  FROM PUBLIC;

CREATE TRIGGER adoption_chat_participants_role_guard
BEFORE INSERT OR UPDATE OF thread_id, user_id, role, last_read_sequence
ON public.adoption_chat_participants
FOR EACH ROW
EXECUTE FUNCTION public.enforce_adoption_chat_participant_role();

INSERT INTO public.adoption_chat_participants (
  thread_id,
  user_id,
  role,
  last_read_at,
  last_read_sequence,
  created_at,
  updated_at
)
SELECT
  id,
  adopter_user_id,
  'adopter'::"AdoptionChatParticipantRole",
  created_at,
  0,
  created_at,
  updated_at
FROM public.adoption_chat_threads
UNION ALL
SELECT
  id,
  shelter_id,
  'shelter'::"AdoptionChatParticipantRole",
  created_at,
  0,
  created_at,
  updated_at
FROM public.adoption_chat_threads;

CREATE TABLE public.adoption_chat_messages (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  sequence_no bigint GENERATED BY DEFAULT AS IDENTITY,
  thread_id uuid NOT NULL,
  sender_user_id uuid NOT NULL,
  body varchar(1000) NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT adoption_chat_messages_pkey PRIMARY KEY (id),
  CONSTRAINT adoption_chat_messages_sequence_key UNIQUE (sequence_no),
  CONSTRAINT adoption_chat_messages_thread_fkey
    FOREIGN KEY (thread_id)
    REFERENCES public.adoption_chat_threads(id)
    ON DELETE CASCADE,
  CONSTRAINT adoption_chat_messages_sender_participant_fkey
    FOREIGN KEY (thread_id, sender_user_id)
    REFERENCES public.adoption_chat_participants(thread_id, user_id)
    ON DELETE CASCADE,
  CONSTRAINT adoption_chat_messages_body_check
    CHECK (char_length(btrim(body)) BETWEEN 1 AND 1000)
);

ALTER TABLE public.media_assets
  ADD COLUMN adoption_chat_message_id uuid;

ALTER TABLE public.media_assets
  ADD CONSTRAINT media_assets_adoption_chat_message_fkey
  FOREIGN KEY (adoption_chat_message_id)
  REFERENCES public.adoption_chat_messages(id)
  ON DELETE CASCADE;

ALTER TABLE public.media_assets
  DROP CONSTRAINT media_assets_entity_count_check;
ALTER TABLE public.media_assets
  ADD CONSTRAINT media_assets_entity_count_check CHECK (
    num_nonnulls(
      draft_id,
      case_id,
      comment_id,
      adoption_chat_message_id
    ) <= 1
    AND (
      status <> 'attached'
      OR num_nonnulls(
        draft_id,
        case_id,
        comment_id,
        adoption_chat_message_id
      ) = 1
    )
  );

ALTER TABLE public.media_assets
  DROP CONSTRAINT media_assets_purpose_entity_check;
ALTER TABLE public.media_assets
  ADD CONSTRAINT media_assets_purpose_entity_check CHECK (
    (
      draft_id IS NULL
      AND case_id IS NULL
      AND comment_id IS NULL
      AND adoption_chat_message_id IS NULL
    )
    OR (comment_id IS NOT NULL AND purpose = 'rescue_comment')
    OR (
      (draft_id IS NOT NULL OR case_id IS NOT NULL)
      AND purpose = 'rescue_case'
    )
    OR (
      adoption_chat_message_id IS NOT NULL
      AND purpose = 'adoption_chat'
    )
  );

CREATE INDEX adoption_chat_participants_user_updated_idx
  ON public.adoption_chat_participants (user_id, updated_at DESC);
CREATE INDEX adoption_chat_messages_thread_sequence_idx
  ON public.adoption_chat_messages (thread_id, sequence_no DESC);
CREATE INDEX media_assets_adoption_chat_message_position_idx
  ON public.media_assets (adoption_chat_message_id, position);
CREATE UNIQUE INDEX media_assets_adoption_chat_message_position_key
  ON public.media_assets (adoption_chat_message_id, position)
  WHERE adoption_chat_message_id IS NOT NULL;

ALTER TABLE public.adoption_chat_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.adoption_chat_messages ENABLE ROW LEVEL SECURITY;

COMMIT;

SELECT 'DAY51_ADOPTION_CHAT_PATCH_PASS' AS status;
